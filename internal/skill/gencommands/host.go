package gencommands

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/muthuishere/aos/internal/cli"
	"github.com/muthuishere/aos/internal/groups"
)

// HostRelPath is the skill's WSL/SSH reference; its table is generated
// between HostBegin and HostEnd, the prose around it is hand-written.
const (
	HostRelPath = "internal/skill/assets/aos/references/host-wsl-ssh.md"
	HostBegin   = "<!-- host-table:begin (generated by go generate ./internal/skill/...; DO NOT EDIT) -->"
	HostEnd     = "<!-- host-table:end -->"
)

// RenderHostTable is one row per group: the public commands that run on the
// Windows host (the person's screen) and the ones that stay inside WSL. Over
// SSH the same split holds, with the person's laptop as the host.
func RenderHostTable() string {
	r := cli.NewRegistry()
	groups.Register(r)
	var b strings.Builder
	b.WriteString("| group | on the Windows host (the screen) | inside WSL (where aos runs) |\n|---|---|---|\n")
	for _, g := range r.Groups() {
		var host, local []string
		for _, c := range g.Commands {
			if c.Hidden || c.Binary != "" {
				continue
			}
			if cli.HostOf(c) == cli.HostWindowsHost {
				host = append(host, leaf(c))
			} else {
				local = append(local, leaf(c))
			}
		}
		if len(host)+len(local) == 0 {
			continue
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", g.Name, cell(host), cell(local))
	}
	b.WriteString("\n`system logout`, `restart` and `shutdown` are never forwarded: taking down the wrong machine is not recoverable.\n")
	return b.String()
}

// leaf is a command as the table shows it; a group that is itself the
// command (aos find, aos version) shows as its full route.
func leaf(c *cli.Command) string {
	if c.Name == "" {
		return "`aos " + c.Group + "`"
	}
	return "`" + c.Name + "`"
}

func cell(names []string) string {
	if len(names) == 0 {
		return ""
	}
	return strings.Join(names, ", ")
}

// SpliceHostTable replaces the generated block in doc.
func SpliceHostTable(doc, table string) (string, error) {
	i := strings.Index(doc, HostBegin)
	j := strings.Index(doc, HostEnd)
	if i < 0 || j < i {
		return "", fmt.Errorf("%s: missing %q / %q markers", HostRelPath, HostBegin, HostEnd)
	}
	return doc[:i+len(HostBegin)] + "\n" + table + doc[j:], nil
}

// WriteHostTable regenerates the table in the skill reference under root.
func WriteHostTable(root string) error {
	path := filepath.Join(root, HostRelPath)
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	out, err := SpliceHostTable(string(data), RenderHostTable())
	if err != nil {
		return err
	}
	return os.WriteFile(path, []byte(out), 0o644)
}
