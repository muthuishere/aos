// Package gencommands renders the skill's references/commands.md from the
// command registry, so the complete index can never drift from the binary.
//
// Regenerate with: go generate ./internal/skill/...
package gencommands

//go:generate go run ./cmd ../../..

import (
	"fmt"
	"strings"

	"github.com/muthuishere/aos/internal/cli"
	"github.com/muthuishere/aos/internal/groups"
)

// RelPath is commands.md relative to the repo root.
const RelPath = "internal/skill/assets/aos/references/commands.md"

// Render returns commands.md for every public (non-hidden) built-in command.
func Render() string {
	r := cli.NewRegistry()
	groups.Register(r)

	var b strings.Builder
	b.WriteString("<!-- Code generated by go generate ./internal/skill/...; DO NOT EDIT. -->\n\n")
	b.WriteString("# aos command index\n\n")
	b.WriteString("Every public command, grouped, generated from the registry. This is the\n")
	b.WriteString("complete list; `aos <group> <cmd> --help` has the full flag set, and\n")
	b.WriteString("`aos commands` says what this particular machine can run right now.\n")
	b.WriteString("Marks: *display* = needs a desktop session (exit 2 without one);\n")
	b.WriteString("*blocking* = runs until stopped; *platforms* = only those OSes.\n")

	for _, g := range r.Groups() {
		var cmds []*cli.Command
		for _, c := range g.Commands {
			if !c.Hidden && c.Binary == "" {
				cmds = append(cmds, c)
			}
		}
		if len(cmds) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n\n", g.Name)
		if g.Description != "" {
			fmt.Fprintf(&b, "%s\n\n", g.Description)
		}
		for _, c := range cmds {
			usage := "aos " + c.Route()
			if c.Args != "" {
				usage += " " + c.Args
			}
			fmt.Fprintf(&b, "### `aos %s`\n\n%s\n\n", c.Route(), c.Summary)
			var marks []string
			if c.NeedsDisplay {
				marks = append(marks, "display")
			}
			if c.Blocking {
				marks = append(marks, "blocking")
			}
			if len(c.Platforms) > 0 {
				marks = append(marks, "platforms: "+strings.Join(c.Platforms, ", "))
			}
			if len(c.Aliases) > 0 {
				marks = append(marks, "alias: "+strings.Join(c.Aliases, ", "))
			}
			if len(marks) > 0 {
				fmt.Fprintf(&b, "*%s*\n\n", strings.Join(marks, " · "))
			}
			fmt.Fprintf(&b, "```bash\n%s\n", usage)
			for _, ex := range c.Examples {
				if ex != usage {
					fmt.Fprintf(&b, "%s\n", ex)
				}
			}
			b.WriteString("```\n\n")
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}
